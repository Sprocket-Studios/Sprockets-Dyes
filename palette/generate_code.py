#!/usr/bin/env python3
"""
Generates code and lang from palette/colors.json:

  src/main/java/io/github/sprocketstudios/sprocketdyes/palette/SprocketPalette.java
      Plain data for all 132 colors in display order. Touches no Minecraft class, so it is safe to
      read from inside DyeColor's static initializer.
  src/main/java/io/github/sprocketstudios/sprocketdyes/palette/NewDyeColorDefinitions.java
      The 116 DyeColor constructor calls (with MapColor references, which get remapped per version).
  src/main/resources/assets/sprocket_dyes/lang/en_us.json  (dye-related keys; block names merged in later)

Run:  python3 palette/generate_code.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = "io.github.sprocketstudios.sprocketdyes.palette"
JAVA_DIR = ROOT / "src/main/java" / Path(*PKG.split("."))
LANG = ROOT / "src/main/resources/assets/sprocket_dyes/lang/en_us.json"
VANILLA_LANG = ROOT / "palette/vanilla_en_us.json"  # optional, extracted from the client jar for banner/firework names

data = json.loads((ROOT / "palette/colors.json").read_text())
hues = data["hues"]
hue_index = {h["id"]: i for i, h in enumerate(hues)}
values = data["values"]
sats = data["sats"]
key = data["key"]
grid = data["colors"]
display = key + grid  # creative/display order: Key first, then hue-major grid order
new = [c for c in grid if not c["vanilla"]]

HEADER = "// GENERATED by palette/generate_code.py from palette/colors.json - do not edit by hand.\n"


def jstr(s):
    return json.dumps(s)


def palette_java():
    rows = []
    for c in display:
        h = -1 if c["hue"] == "key" else hue_index[c["hue"]]
        s = -1 if c["sat"] is None else sats.index(c["sat"])
        v = -1 if c["value"] is None else values.index(c["value"])
        rows.append(
            f'        new Entry({jstr(c["id"])}, {jstr(c["name"])}, {h}, {s}, {v}, 0x{c["hex"]}, {str(c["vanilla"]).lower()}, '
            f'{jstr(c["source"])}, {jstr(c["glazed"])})'
        )
    hue_rows = ",\n".join(f'        new Hue({jstr(h["id"])}, {jstr(h["name"])})' for h in hues)
    return f"""{HEADER}package {PKG};

import java.util.List;

/**
 * The Sprocket Dyes palette: the 4 Key dyes, then 16 hues x {{standard, muted}} x {{bright, medium, deep, dark}}.
 * Vanilla colors appear with {{@code vanilla = true}} and their vanilla ids.
 */
public final class SprocketPalette {{
    private SprocketPalette() {{}}

    public static final List<String> VALUES = List.of({", ".join(jstr(v) for v in values)});
    public static final List<String> SATURATIONS = List.of({", ".join(jstr(s) for s in sats)});

    /** A hue section. Index into {{@link #HUES}} is the hue's position on the wheel (red = 0). */
    public record Hue(String id, String name) {{}}

    /**
     * One color.
     *
     * @param hue        index into {{@link #HUES}}, or -1 for a Key color
     * @param saturation index into {{@link #SATURATIONS}}, or -1 for a Key color
     * @param value      index into {{@link #VALUES}}, or -1 for a Key color
     * @param rgb        texture diffuse color
     * @param source     vanilla color its textures are recolored from
     * @param glazed     vanilla color whose glazed terracotta pattern it uses
     */
    public record Entry(String id, String name, int hue, int saturation, int value, int rgb, boolean vanilla, String source, String glazed) {{
        public boolean isKey() {{
            return hue < 0;
        }}
    }}

    public static final List<Hue> HUES = List.of(
{hue_rows}
    );

    /** All {len(display)} colors in display order: Key, then each hue's 8 points. */
    public static final List<Entry> ALL = List.of(
{",\n".join(rows)}
    );

    /** Number of colors added on top of vanilla's 16. */
    public static final int NEW_COLOR_COUNT = {len(new)};
}}
"""


def definitions_java():
    rows = []
    for i, c in enumerate(new):
        rows.append(
            f'        factory.create({jstr(c["id"].upper())}, {16 + i}, {jstr(c["id"])}, 0x{c["hex"]}, '
            f'MapColor.{c["map_color"]}, MapColor.{c["terracotta_map_color"]}, 0x{c["firework"]}, 0x{c["text"]});'
        )
    return f"""{HEADER}package {PKG};

import net.minecraft.world.level.material.MapColor;

/** Constructor arguments for the {len(new)} new {{@code DyeColor}} constants, ids 16-{15 + len(new)}. */
public final class NewDyeColorDefinitions {{
    private NewDyeColorDefinitions() {{}}

    @FunctionalInterface
    public interface Factory {{
        void create(String constant, int id, String name, int textureDiffuseColor, MapColor mapColor, MapColor terracottaColor, int fireworkColor, int textColor);
    }}

    public static void define(Factory factory) {{
{chr(10).join(rows)}
    }}
}}
"""


def lang():
    out = json.loads(LANG.read_text()) if LANG.exists() else {}
    # Drop previously generated dye keys so renames don't leave stale entries behind.
    out = {k: v for k, v in out.items() if not k.startswith(("item.sprocket_dyes.", "color.minecraft.", "sprocket_dyes.hue.", "sprocket_dyes.sat.", "sprocket_dyes.value."))}
    out["sprocket_dyes.tooltip.position"] = "%1$s · %2$s · %3$s"
    out["sprocket_dyes.hue.key"] = "Key"
    for h in hues:
        out[f"sprocket_dyes.hue.{h['id']}"] = h["name"]
    for s in sats:
        out[f"sprocket_dyes.sat.{s}"] = s.capitalize()
    for v in values:
        out[f"sprocket_dyes.value.{v}"] = v.capitalize()
    for c in new:
        out[f"item.sprocket_dyes.{c['id']}_dye"] = f"{c['name']} Dye"
        out[f"color.minecraft.{c['id']}"] = c["name"]
        out[f"item.minecraft.firework_star.{c['id']}"] = c["name"]
    return dict(sorted(out.items()))


def main():
    JAVA_DIR.mkdir(parents=True, exist_ok=True)
    (JAVA_DIR / "SprocketPalette.java").write_text(palette_java())
    (JAVA_DIR / "NewDyeColorDefinitions.java").write_text(definitions_java())
    LANG.parent.mkdir(parents=True, exist_ok=True)
    LANG.write_text(json.dumps(lang(), indent=2, ensure_ascii=False) + "\n")
    print(f"wrote SprocketPalette.java ({len(display)} colors), NewDyeColorDefinitions.java ({len(new)} new), {LANG.name}")


if __name__ == "__main__":
    main()
